-- Design orders. One row per paid order, plus one row per design bought in it.
-- Idempotent: safe to re-run.
--
-- Design notes
--  * Amounts are NUMERIC rupees. total = items_total + platform_fee (checked).
--  * customer_id is SET NULL if the customer is deleted, so a deletion never erases an order;
--    mobile_number keeps who bought it.
--  * order_items keep a snapshot (name, image, prices) because designs can be renamed or deleted.
--    Designs live in one table per category, so the link is (design_category, design_id), not a foreign key.

CREATE TABLE IF NOT EXISTS orders (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id          BIGINT REFERENCES users (customer_id) ON DELETE SET NULL,
  mobile_number        VARCHAR(20)   NOT NULL,
  items_total          NUMERIC(10,2) NOT NULL CHECK (items_total >= 0),
  platform_fee         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (platform_fee >= 0),
  total                NUMERIC(10,2) NOT NULL CHECK (total >= 0),
  currency             CHAR(3)       NOT NULL DEFAULT 'INR',
  payment_status       VARCHAR(20)   NOT NULL DEFAULT 'pending'
                       CHECK (payment_status IN ('pending', 'captured', 'failed', 'refunded')),
  razorpay_order_id    VARCHAR(40)   NOT NULL UNIQUE,
  razorpay_payment_id  VARCHAR(40)   NOT NULL UNIQUE,
  razorpay_signature   VARCHAR(128),
  email_sent           BOOLEAN       NOT NULL DEFAULT FALSE,
  created_at           TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  CONSTRAINT orders_total_adds_up CHECK (total = items_total + platform_fee)
);
CREATE INDEX IF NOT EXISTS orders_customer_idx ON orders (customer_id);
CREATE INDEX IF NOT EXISTS orders_mobile_idx ON orders (mobile_number);
CREATE INDEX IF NOT EXISTS orders_created_idx ON orders (created_at DESC);

CREATE TABLE IF NOT EXISTS order_items (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id         BIGINT        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  position         SMALLINT      NOT NULL CHECK (position >= 1),
  design_id        BIGINT,
  design_category  VARCHAR(20)
                   CHECK (design_category IN ('butta', 'brocade', 'border', 'pallu', 'pattern', 'full_set', 'free_image')),
  design_name      VARCHAR(100)  NOT NULL,
  image_url        TEXT          NOT NULL,
  price            NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  final_price      NUMERIC(10,2) NOT NULL CHECK (final_price >= 0),
  CONSTRAINT order_items_category_needs_id CHECK (design_category IS NULL OR design_id IS NOT NULL),
  CONSTRAINT order_items_unique_position UNIQUE (order_id, position)
);
CREATE INDEX IF NOT EXISTS order_items_design_idx ON order_items (design_category, design_id);
