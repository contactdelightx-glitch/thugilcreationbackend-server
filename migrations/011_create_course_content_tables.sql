-- Course content: curriculum, files and reviews. Idempotent: safe to re-run.
--
--   course_sections        a course is split into sections
--   course_videos          the videos inside a section
--   course_resources       practice files, attached to a video
--   course_software_links  software the course needs
--   course_learning_points the "what you will learn" list
--   course_reviews         student ratings
--   course_promotions      promo banners for a course
--
-- position = display order (1, 2, 3 ...), unique inside its parent.

CREATE TABLE IF NOT EXISTS course_sections (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id    BIGINT      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  title        TEXT        NOT NULL,
  description  TEXT,
  position     INTEGER     NOT NULL CHECK (position >= 0),
  is_published BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT course_sections_unique_position UNIQUE (course_id, position)
);

CREATE TABLE IF NOT EXISTS course_videos (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id            BIGINT      NOT NULL REFERENCES course_sections (id) ON DELETE CASCADE,
  title                 TEXT        NOT NULL,
  description           TEXT,
  video_url             TEXT,
  bunny_video_id        VARCHAR(60),
  thumbnail_url         TEXT,
  duration_seconds      INTEGER     CHECK (duration_seconds >= 0),
  position              INTEGER     NOT NULL CHECK (position >= 0),
  is_free_preview       BOOLEAN     NOT NULL DEFAULT FALSE,
  is_published          BOOLEAN     NOT NULL DEFAULT FALSE,
  encoding_status       VARCHAR(20),
  upload_status         VARCHAR(20),
  needs_client_upload   BOOLEAN     NOT NULL DEFAULT FALSE,
  available_resolutions TEXT[]      NOT NULL DEFAULT '{}',
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT course_videos_unique_position UNIQUE (section_id, position)
);
CREATE INDEX IF NOT EXISTS course_videos_section_idx ON course_videos (section_id);

CREATE TABLE IF NOT EXISTS course_resources (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id      BIGINT      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  video_id       BIGINT      REFERENCES course_videos (id) ON DELETE SET NULL,
  title          TEXT        NOT NULL,
  description    TEXT,
  resource_type  VARCHAR(30) NOT NULL DEFAULT 'practice_file',
  file_url       TEXT,
  file_name      VARCHAR(255),
  file_size      BIGINT      CHECK (file_size >= 0),
  mime_type      VARCHAR(100),
  thumbnail_url  TEXT,
  position       INTEGER     NOT NULL DEFAULT 1 CHECK (position >= 0),
  is_published   BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS course_resources_course_idx ON course_resources (course_id);
CREATE INDEX IF NOT EXISTS course_resources_video_idx ON course_resources (video_id);

CREATE TABLE IF NOT EXISTS course_software_links (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id                 BIGINT      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  name                      VARCHAR(200) NOT NULL,
  description               TEXT,
  download_url              TEXT        NOT NULL,
  version                   VARCHAR(50),
  file_size                 VARCHAR(50),
  platform                  VARCHAR(50),
  installation_instructions TEXT,
  is_required               BOOLEAN     NOT NULL DEFAULT FALSE,
  position                  INTEGER     NOT NULL DEFAULT 1 CHECK (position >= 0),
  created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at                TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS course_software_course_idx ON course_software_links (course_id);

CREATE TABLE IF NOT EXISTS course_learning_points (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id   BIGINT      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  text        TEXT        NOT NULL,
  position    INTEGER     NOT NULL CHECK (position >= 0),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS course_learning_points_course_idx ON course_learning_points (course_id);

CREATE TABLE IF NOT EXISTS course_reviews (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id     BIGINT      NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  customer_id   BIGINT      REFERENCES users (customer_id) ON DELETE SET NULL,
  reviewer_name VARCHAR(150),
  rating        SMALLINT    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review_text   TEXT,
  is_published  BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS course_reviews_course_idx ON course_reviews (course_id);
-- one review per student per course
CREATE UNIQUE INDEX IF NOT EXISTS course_reviews_one_per_student ON course_reviews (course_id, customer_id) WHERE customer_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS course_promotions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id    BIGINT      REFERENCES courses (id) ON DELETE SET NULL,
  title        TEXT        NOT NULL,
  message      TEXT,
  sub_text     TEXT,
  button_text  VARCHAR(100),
  image_url    TEXT,
  is_active    BOOLEAN     NOT NULL DEFAULT TRUE,
  target_users VARCHAR(30) NOT NULL DEFAULT 'all',
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

