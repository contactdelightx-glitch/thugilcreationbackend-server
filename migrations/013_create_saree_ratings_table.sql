-- Star ratings (with an optional review) from the saree site (source: Supabase sareerating).
-- A rating is either for one design, or a general rating of the site (design_id is NULL).
-- Designs live in one table per category, so the link is (design_category, design_id), not a foreign key:
-- the rating stays even if the design is later deleted. Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS saree_ratings (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  design_id        BIGINT,
  design_category  VARCHAR(20)
                   CHECK (design_category IN ('butta', 'brocade', 'border', 'pallu', 'pattern', 'full_set', 'free_image')),
  rating           SMALLINT    NOT NULL CHECK (rating BETWEEN 1 AND 5),
  review           TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT saree_ratings_category_needs_id CHECK (design_category IS NULL OR design_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS saree_ratings_design_idx ON saree_ratings (design_category, design_id);
CREATE INDEX IF NOT EXISTS saree_ratings_created_idx ON saree_ratings (created_at DESC);
