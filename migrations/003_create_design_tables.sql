-- One table per saree style. Idempotent: safe to re-run.
--
--   Weave designs (same fields): butta, brocade, border, pallu, pattern
--   Full set  : own fields (jacquard type, body/border epi, hook counts)
--   Free image: image + redirect link only

-- ---------- Weave designs: butta, brocade, border, pallu, pattern ----------
DO $$
DECLARE
  t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['butta_designs', 'brocade_designs', 'border_designs', 'pallu_designs', 'pattern_designs']
  LOOP
    EXECUTE format($f$
      CREATE TABLE IF NOT EXISTS %1$I (
        id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id          VARCHAR(40)   NOT NULL UNIQUE,
        name                VARCHAR(100)  NOT NULL,
        designer_email      VARCHAR(255)  NOT NULL,
        cards               INTEGER       NOT NULL CHECK (cards >= 0),
        hooks               INTEGER       NOT NULL CHECK (hooks >= 0),
        epi                 INTEGER       NOT NULL CHECK (epi > 0),
        ppi                 INTEGER       NOT NULL CHECK (ppi > 0),
        harness_build       VARCHAR(30),
        image_type          VARCHAR(10)   NOT NULL CHECK (image_type IN ('BMP', 'JPG', 'PNG')),
        image_url           TEXT          NOT NULL,
        original_image_url  TEXT          NOT NULL,
        label               VARCHAR(20)   NOT NULL DEFAULT 'new' CHECK (label IN ('new', 'sale', 'featured')),
        listing_rate        NUMERIC(10,2) NOT NULL CHECK (listing_rate >= 0),
        final_price         NUMERIC(10,2) NOT NULL CHECK (final_price >= 0),
        notes               TEXT,
        created_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
        updated_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW()
      )$f$, t);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (designer_email)', t || '_designer_idx', t);
    EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I (label)', t || '_label_idx', t);
  END LOOP;
END $$;

-- ---------- Full set ----------
CREATE TABLE IF NOT EXISTS full_set_designs (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id          VARCHAR(40)   NOT NULL UNIQUE,
  name                VARCHAR(100)  NOT NULL,
  designer_email      VARCHAR(255)  NOT NULL,
  jacquard_type       VARCHAR(20)   NOT NULL CHECK (jacquard_type IN ('powerloom', 'rapier', 'handloom')),
  ppi                 INTEGER       NOT NULL CHECK (ppi > 0),
  body_epi            INTEGER       NOT NULL CHECK (body_epi > 0),
  border_epi          INTEGER       CHECK (border_epi > 0),
  br_hooks            VARCHAR(100),   -- text: values like '248*2(DOUBLE)'
  by_hooks            VARCHAR(100),   -- text: values like '480+880(440*2)'
  image_type          VARCHAR(10)   NOT NULL CHECK (image_type IN ('BMP', 'JPG', 'PNG')),
  image_url           TEXT          NOT NULL,
  original_image_url  TEXT          NOT NULL,
  label               VARCHAR(20)   NOT NULL DEFAULT 'new' CHECK (label IN ('new', 'sale', 'featured')),
  listing_rate        NUMERIC(10,2) NOT NULL CHECK (listing_rate >= 0),
  final_price         NUMERIC(10,2) NOT NULL CHECK (final_price >= 0),
  created_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS full_set_designs_designer_idx ON full_set_designs (designer_email);
CREATE INDEX IF NOT EXISTS full_set_designs_label_idx ON full_set_designs (label);

-- ---------- Free image ----------
CREATE TABLE IF NOT EXISTS free_image_designs (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id          VARCHAR(40)   NOT NULL UNIQUE,
  designer_email      VARCHAR(255)  NOT NULL,
  image_url           TEXT          NOT NULL,
  original_image_url  TEXT          NOT NULL,
  redirect_url        TEXT          NOT NULL,
  label               VARCHAR(20)   NOT NULL DEFAULT 'new' CHECK (label IN ('new', 'sale', 'featured')),
  listing_rate        NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (listing_rate >= 0),
  final_price         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (final_price >= 0),
  created_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at          TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS free_image_designs_designer_idx ON free_image_designs (designer_email);
