-- Student questions about a course (or one video in it), and the admin's answers.
-- Idempotent: safe to re-run.
--
--   status: pending  = waiting for an answer
--           answered = the admin has written an answer (answer and answered_at are then always set)
--
-- customer_id is SET NULL if the account is deleted; student_name / student_email keep who asked.

CREATE TABLE IF NOT EXISTS course_doubts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id    BIGINT       REFERENCES users (customer_id) ON DELETE SET NULL,
  student_name   VARCHAR(150),
  student_email  VARCHAR(255) NOT NULL,
  course_id      BIGINT       NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
  video_id       BIGINT       REFERENCES course_videos (id) ON DELETE SET NULL,
  question       TEXT         NOT NULL CHECK (length(btrim(question)) > 0),
  answer         TEXT,
  status         VARCHAR(20)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'answered')),
  answered_at    TIMESTAMPTZ,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  CONSTRAINT course_doubts_answer_matches_status
    CHECK ((status = 'answered') = (answer IS NOT NULL AND answered_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS course_doubts_status_idx ON course_doubts (status, created_at);
CREATE INDEX IF NOT EXISTS course_doubts_course_idx ON course_doubts (course_id);
CREATE INDEX IF NOT EXISTS course_doubts_customer_idx ON course_doubts (customer_id);
