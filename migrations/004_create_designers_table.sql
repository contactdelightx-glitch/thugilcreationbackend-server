-- Designers: the accounts a design can belong to (source: Supabase public.users).
-- Passwords are intentionally not stored here. Idempotent: safe to re-run.

CREATE TABLE IF NOT EXISTS designers (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR(255) NOT NULL,
  type        VARCHAR(20)  NOT NULL DEFAULT 'tenant' CHECK (type IN ('tenant', 'superadmin')),
  status      VARCHAR(20)  NOT NULL DEFAULT 'active',
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- case-insensitive unique email
CREATE UNIQUE INDEX IF NOT EXISTS designers_email_lower_uidx ON designers (LOWER(email));
