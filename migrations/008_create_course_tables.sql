-- Course enrollments (students). Idempotent: safe to re-run.
--
--   course_categories      course topics
--   courses                what can be enrolled in
--   enrollments            a student buying a course: pricing, payment, access and progress
--   certificates              certificate request/issue details (only exists once requested)
--   enrollment_video_progress  one row per video a student has watched
--
-- Amounts are NUMERIC rupees and must add up: amount_paid = base_price - discount + certificate + doubt support.
-- A student is simply an account in `users` that has a completed enrollment here.
-- customer_id is SET NULL if the account is deleted, so an enrollment (and its payment) is never erased;
-- student_name / student_email keep who it was.

CREATE TABLE IF NOT EXISTS course_categories (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(100) NOT NULL UNIQUE,
  description  TEXT,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS courses (
  id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title                      TEXT          NOT NULL,
  description                TEXT,
  instructor_name            VARCHAR(100)  NOT NULL,
  price                      NUMERIC(10,2) NOT NULL CHECK (price >= 0),
  certificate_with_price     NUMERIC(10,2) CHECK (certificate_with_price >= 0),
  certificate_without_price  NUMERIC(10,2) CHECK (certificate_without_price >= 0),
  is_published               BOOLEAN       NOT NULL DEFAULT FALSE,
  status                     VARCHAR(20)   NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
  category_id                INTEGER REFERENCES course_categories (id) ON DELETE SET NULL,
  thumbnail_url              TEXT,
  language                   VARCHAR(50),
  duration                   VARCHAR(50),
  duration_months            SMALLINT CHECK (duration_months >= 0),
  created_at                 TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at                 TIMESTAMPTZ   NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS enrollments (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id             BIGINT REFERENCES users (customer_id) ON DELETE SET NULL,
  student_name            VARCHAR(150),
  student_email           VARCHAR(255)  NOT NULL,
  course_id               BIGINT        NOT NULL REFERENCES courses (id) ON DELETE RESTRICT,
  enrollment_type         VARCHAR(20)   NOT NULL DEFAULT 'purchase',
  payment_status          VARCHAR(20)   NOT NULL CHECK (payment_status IN ('pending', 'completed', 'failed', 'refunded')),

  base_price              NUMERIC(10,2) NOT NULL CHECK (base_price >= 0),
  discount_percentage     NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (discount_percentage BETWEEN 0 AND 100),
  discount_amount         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  certificate_included    BOOLEAN       NOT NULL DEFAULT FALSE,
  certificate_fee         NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (certificate_fee >= 0),
  doubt_support_included  BOOLEAN       NOT NULL DEFAULT FALSE,
  doubt_support_fee       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (doubt_support_fee >= 0),
  amount_paid             NUMERIC(10,2) NOT NULL CHECK (amount_paid >= 0),
  currency                CHAR(3)       NOT NULL DEFAULT 'INR',

  payment_method          VARCHAR(30),
  transaction_id          VARCHAR(80)  UNIQUE,
  razorpay_order_id       VARCHAR(40)  UNIQUE,
  razorpay_payment_id     VARCHAR(40)  UNIQUE,

  enrolled_at             TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  expires_at              TIMESTAMPTZ,
  access_duration_days    INTEGER CHECK (access_duration_days > 0),
  last_accessed_at        TIMESTAMPTZ,
  is_active               BOOLEAN       NOT NULL DEFAULT TRUE,

  progress_percentage     SMALLINT      NOT NULL DEFAULT 0 CHECK (progress_percentage BETWEEN 0 AND 100),
  is_completed            BOOLEAN       NOT NULL DEFAULT FALSE,
  completed_at            TIMESTAMPTZ,

  purchase_count          INTEGER       NOT NULL DEFAULT 1 CHECK (purchase_count >= 1),
  previous_enrollment_id  BIGINT REFERENCES enrollments (id) ON DELETE SET NULL,

  created_at              TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  updated_at              TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
  CONSTRAINT enrollments_amount_adds_up
    CHECK (amount_paid = base_price - discount_amount + certificate_fee + doubt_support_fee)
);
CREATE INDEX IF NOT EXISTS enrollments_customer_idx ON enrollments (customer_id);
CREATE INDEX IF NOT EXISTS enrollments_course_idx ON enrollments (course_id);
CREATE INDEX IF NOT EXISTS enrollments_enrolled_idx ON enrollments (enrolled_at DESC);

CREATE TABLE IF NOT EXISTS certificates (
  enrollment_id       BIGINT PRIMARY KEY REFERENCES enrollments (id) ON DELETE CASCADE,
  status              VARCHAR(20) NOT NULL CHECK (status IN ('requested', 'issued')),
  certificate_number  VARCHAR(60) UNIQUE,
  full_name           VARCHAR(150),
  title               VARCHAR(20),
  delivery_email      VARCHAR(255),
  shipping_address    TEXT,
  requested_at        TIMESTAMPTZ,
  issued_at           TIMESTAMPTZ,
  CONSTRAINT certificate_issued_has_number CHECK (status <> 'issued' OR (certificate_number IS NOT NULL AND issued_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS enrollment_video_progress (
  enrollment_id        BIGINT        NOT NULL REFERENCES enrollments (id) ON DELETE CASCADE,
  video_id             INTEGER       NOT NULL,
  duration_seconds     NUMERIC(10,3),
  position_seconds     NUMERIC(10,3),
  max_position_seconds NUMERIC(10,3),
  last_played_at       TIMESTAMPTZ,
  is_completed         BOOLEAN       NOT NULL DEFAULT FALSE,
  PRIMARY KEY (enrollment_id, video_id)
);
